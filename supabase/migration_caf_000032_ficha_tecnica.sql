-- 1. Tabela de Fichas Técnicas (Insumos por Produto ou Adicional)
CREATE TABLE IF NOT EXISTS public.fichas_tecnicas (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  produto_id TEXT REFERENCES public.produtos(id) ON DELETE CASCADE,
  adicional_id TEXT REFERENCES public.adicionais(id) ON DELETE CASCADE,
  estoque_item_id BIGINT NOT NULL REFERENCES public.estoque_itens(id) ON DELETE RESTRICT,
  quantidade NUMERIC(12,3) NOT NULL CHECK (quantidade > 0),
  created_at TIMESTAMPTZ DEFAULT timezone('America/Sao_Paulo', now()) NOT NULL,
  CONSTRAINT chk_ficha_dono CHECK (
    (produto_id IS NOT NULL AND adicional_id IS NULL) OR
    (produto_id IS NULL AND adicional_id IS NOT NULL)
  ),
  CONSTRAINT uq_ficha_prod_item UNIQUE (produto_id, estoque_item_id),
  CONSTRAINT uq_ficha_adic_item UNIQUE (adicional_id, estoque_item_id)
);

CREATE INDEX IF NOT EXISTS idx_fichas_tecnicas_produto ON public.fichas_tecnicas(produto_id);
CREATE INDEX IF NOT EXISTS idx_fichas_tecnicas_adicional ON public.fichas_tecnicas(adicional_id);
CREATE INDEX IF NOT EXISTS idx_fichas_tecnicas_estoque_item ON public.fichas_tecnicas(estoque_item_id);

-- 2. Colunas de Preço de Custo e Registro Histórico no Pedido
ALTER TABLE public.produtos 
  ADD COLUMN IF NOT EXISTS preco_custo_manual NUMERIC(10,2);

ALTER TABLE public.pedido_itens 
  ADD COLUMN IF NOT EXISTS custo_unitario NUMERIC(10,4) DEFAULT 0;

ALTER TABLE public.pedido_item_adicionais 
  ADD COLUMN IF NOT EXISTS custo NUMERIC(10,4) DEFAULT 0;

-- 3. Função para Calcular Custo Unitário do Produto (com base na ficha ou custo manual)
CREATE OR REPLACE FUNCTION public.fn_calcular_custo_produto(p_produto_id TEXT)
RETURNS NUMERIC(10,4) AS $$
DECLARE
  v_custo_ficha NUMERIC(10,4) := 0;
  v_has_ficha BOOLEAN := false;
  v_custo_manual NUMERIC(10,2);
  v_estoque_item_id BIGINT;
  v_custo_estoque NUMERIC(10,4);
BEGIN
  -- 1. Verifica se há insumos na ficha técnica
  SELECT COALESCE(SUM(ft.quantidade * COALESCE(ei.custo_unitario_medio, 0)), 0), true
  INTO v_custo_ficha, v_has_ficha
  FROM public.fichas_tecnicas ft
  JOIN public.estoque_itens ei ON ei.id = ft.estoque_item_id
  WHERE ft.produto_id = p_produto_id;

  IF v_has_ficha AND v_custo_ficha > 0 THEN
    RETURN v_custo_ficha;
  END IF;

  -- 2. Se não houver ficha com custo, consulta custo manual ou item de revenda direta
  SELECT preco_custo_manual, estoque_item_id
  INTO v_custo_manual, v_estoque_item_id
  FROM public.produtos
  WHERE id = p_produto_id;

  IF v_custo_manual IS NOT NULL AND v_custo_manual > 0 THEN
    RETURN v_custo_manual::NUMERIC(10,4);
  END IF;

  IF v_estoque_item_id IS NOT NULL THEN
    SELECT COALESCE(custo_unitario_medio, 0) INTO v_custo_estoque
    FROM public.estoque_itens
    WHERE id = v_estoque_item_id;
    RETURN COALESCE(v_custo_estoque, 0);
  END IF;

  RETURN 0;
END;
$$ LANGUAGE plpgsql STABLE SECURITY DEFINER;

-- 4. Função para Calcular Custo de Adicional
CREATE OR REPLACE FUNCTION public.fn_calcular_custo_adicional(p_adicional_id TEXT)
RETURNS NUMERIC(10,4) AS $$
DECLARE
  v_custo_ficha NUMERIC(10,4) := 0;
  v_has_ficha BOOLEAN := false;
  v_estoque_item_id BIGINT;
  v_custo_estoque NUMERIC(10,4);
BEGIN
  -- 1. Ficha técnica do adicional
  SELECT COALESCE(SUM(ft.quantidade * COALESCE(ei.custo_unitario_medio, 0)), 0), true
  INTO v_custo_ficha, v_has_ficha
  FROM public.fichas_tecnicas ft
  JOIN public.estoque_itens ei ON ei.id = ft.estoque_item_id
  WHERE ft.adicional_id = p_adicional_id;

  IF v_has_ficha AND v_custo_ficha > 0 THEN
    RETURN v_custo_ficha;
  END IF;

  -- 2. Insumo direto de estoque
  SELECT estoque_item_id INTO v_estoque_item_id
  FROM public.adicionais
  WHERE id = p_adicional_id;

  IF v_estoque_item_id IS NOT NULL THEN
    SELECT COALESCE(custo_unitario_medio, 0) INTO v_custo_estoque
    FROM public.estoque_itens
    WHERE id = v_estoque_item_id;
    RETURN COALESCE(v_custo_estoque, 0);
  END IF;

  RETURN 0;
END;
$$ LANGUAGE plpgsql STABLE SECURITY DEFINER;

-- 5. Trigger BEFORE INSERT em pedido_itens para gravar o custo no momento da venda
CREATE OR REPLACE FUNCTION public.fn_gravar_custo_pedido_item()
RETURNS TRIGGER AS $$
BEGIN
  IF NEW.custo_unitario IS NULL OR NEW.custo_unitario = 0 THEN
    NEW.custo_unitario := public.fn_calcular_custo_produto(NEW.produto_id);
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS trg_gravar_custo_pedido_item ON public.pedido_itens;
CREATE TRIGGER trg_gravar_custo_pedido_item
  BEFORE INSERT ON public.pedido_itens
  FOR EACH ROW
  EXECUTE FUNCTION public.fn_gravar_custo_pedido_item();

-- 6. Trigger Atualizada de Baixa de Estoque em pedido_itens
-- Suporta: Ficha Técnica (múltiplos insumos) OU Revenda Direta (estoque_item_id)
CREATE OR REPLACE FUNCTION public.fn_baixa_estoque_pedido_item()
RETURNS TRIGGER AS $$
DECLARE
  v_estoque_item_id BIGINT;
  v_tipo_montagem TEXT;
  v_ft RECORD;
  v_has_ficha BOOLEAN := false;
BEGIN
  IF NEW.cancelado = true THEN
    RETURN NEW;
  END IF;

  SELECT tipo_montagem, estoque_item_id INTO v_tipo_montagem, v_estoque_item_id
  FROM public.produtos
  WHERE id = NEW.produto_id;

  -- Se for meio a meio, a baixa será feita pela tabela pedido_item_sabores
  IF v_tipo_montagem = 'meio_a_meio' THEN
    RETURN NEW;
  END IF;

  -- 1. Verifica se há ficha técnica para o produto
  FOR v_ft IN
    SELECT estoque_item_id, quantidade
    FROM public.fichas_tecnicas
    WHERE produto_id = NEW.produto_id
  LOOP
    v_has_ficha := true;
    INSERT INTO public.estoque_movimentos (
      item_id, tipo, quantidade, pedido_item_id, motivo, criado_por, created_at
    ) VALUES (
      v_ft.estoque_item_id,
      'saida_venda',
      (NEW.quantidade * v_ft.quantidade),
      NEW.id,
      'Venda ' || NEW.nome_produto || ' (Item #' || NEW.id || ')',
      auth.uid(),
      timezone('America/Sao_Paulo', now())
    );
  END LOOP;

  -- 2. Se não houver ficha, verificar produto de revenda direta
  IF NOT v_has_ficha AND v_estoque_item_id IS NOT NULL THEN
    INSERT INTO public.estoque_movimentos (
      item_id, tipo, quantidade, pedido_item_id, motivo, criado_por, created_at
    ) VALUES (
      v_estoque_item_id,
      'saida_venda',
      NEW.quantidade,
      NEW.id,
      'Venda Revenda ' || NEW.nome_produto || ' (Item #' || NEW.id || ')',
      auth.uid(),
      timezone('America/Sao_Paulo', now())
    );
  END IF;

  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- 7. Trigger para Baixa de Estoque em pedido_item_sabores (Meio a Meio: 50% de cada ficha)
CREATE OR REPLACE FUNCTION public.fn_baixa_estoque_meio_a_meio()
RETURNS TRIGGER AS $$
DECLARE
  v_qtd_pai INT := 1;
  v_ft RECORD;
  v_has_ficha BOOLEAN := false;
  v_estoque_item_id BIGINT;
  v_nome_produto TEXT;
  v_custo_total_sabores NUMERIC(10,4) := 0;
BEGIN
  -- Busca quantidade do item pai
  SELECT COALESCE(quantidade, 1) INTO v_qtd_pai
  FROM public.pedido_itens
  WHERE id = NEW.pedido_item_id;

  SELECT nome, estoque_item_id INTO v_nome_produto, v_estoque_item_id
  FROM public.produtos
  WHERE id = NEW.produto_id;

  -- 1. Baixa 50% de cada insumo da ficha técnica do sabor
  FOR v_ft IN
    SELECT estoque_item_id, quantidade
    FROM public.fichas_tecnicas
    WHERE produto_id = NEW.produto_id
  LOOP
    v_has_ficha := true;
    INSERT INTO public.estoque_movimentos (
      item_id, tipo, quantidade, pedido_item_id, motivo, criado_por, created_at
    ) VALUES (
      v_ft.estoque_item_id,
      'saida_venda',
      (v_qtd_pai * 0.5 * v_ft.quantidade),
      NEW.pedido_item_id,
      'Meio a Meio (' || NEW.lado || '): ' || COALESCE(v_nome_produto, NEW.nome),
      auth.uid(),
      timezone('America/Sao_Paulo', now())
    );
  END LOOP;

  -- 2. Se sabor não tem ficha mas tem estoque_item_id direto
  IF NOT v_has_ficha AND v_estoque_item_id IS NOT NULL THEN
    INSERT INTO public.estoque_movimentos (
      item_id, tipo, quantidade, pedido_item_id, motivo, criado_por, created_at
    ) VALUES (
      v_estoque_item_id,
      'saida_venda',
      (v_qtd_pai * 0.5),
      NEW.pedido_item_id,
      'Meio a Meio (' || NEW.lado || '): ' || COALESCE(v_nome_produto, NEW.nome),
      auth.uid(),
      timezone('America/Sao_Paulo', now())
    );
  END IF;

  -- 3. Recalcular e atualizar o custo_unitario no item pai (soma de 0.5 * custo de cada sabor)
  SELECT COALESCE(SUM(ROUND(public.fn_calcular_custo_produto(pis.produto_id) * 0.5, 4)), 0)
  INTO v_custo_total_sabores
  FROM public.pedido_item_sabores pis
  WHERE pis.pedido_item_id = NEW.pedido_item_id;

  IF v_custo_total_sabores > 0 THEN
    UPDATE public.pedido_itens
    SET custo_unitario = v_custo_total_sabores
    WHERE id = NEW.pedido_item_id;
  END IF;

  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS trg_baixa_estoque_meio_a_meio ON public.pedido_item_sabores;
CREATE TRIGGER trg_baixa_estoque_meio_a_meio
  AFTER INSERT ON public.pedido_item_sabores
  FOR EACH ROW
  EXECUTE FUNCTION public.fn_baixa_estoque_meio_a_meio();

-- 8. Trigger Atualizada de Baixa de Estoque para Adicionais
CREATE OR REPLACE FUNCTION public.fn_baixa_estoque_adicional()
RETURNS TRIGGER AS $$
DECLARE
  v_estoque_item_id BIGINT;
  v_qtd_pai INT := 1;
  v_ft RECORD;
  v_has_ficha BOOLEAN := false;
  v_custo_adic NUMERIC(10,4);
BEGIN
  SELECT COALESCE(quantidade, 1) INTO v_qtd_pai
  FROM public.pedido_itens
  WHERE id = NEW.pedido_item_id;

  -- 1. Baixar insumos se houver ficha técnica
  FOR v_ft IN
    SELECT estoque_item_id, quantidade
    FROM public.fichas_tecnicas
    WHERE adicional_id = NEW.adicional_id
  LOOP
    v_has_ficha := true;
    INSERT INTO public.estoque_movimentos (
      item_id, tipo, quantidade, pedido_item_id, motivo, criado_por, created_at
    ) VALUES (
      v_ft.estoque_item_id,
      'saida_venda',
      (v_qtd_pai * COALESCE(NEW.quantidade, 1) * v_ft.quantidade),
      NEW.pedido_item_id,
      'Adicional ' || NEW.nome,
      auth.uid(),
      timezone('America/Sao_Paulo', now())
    );
  END LOOP;

  -- 2. Se não houver ficha, verificar estoque_item_id direto
  IF NOT v_has_ficha THEN
    SELECT estoque_item_id INTO v_estoque_item_id
    FROM public.adicionais
    WHERE id = NEW.adicional_id;

    IF v_estoque_item_id IS NOT NULL THEN
      INSERT INTO public.estoque_movimentos (
        item_id, tipo, quantidade, pedido_item_id, motivo, criado_por, created_at
      ) VALUES (
        v_estoque_item_id,
        'saida_venda',
        (v_qtd_pai * COALESCE(NEW.quantidade, 1)),
        NEW.pedido_item_id,
        'Adicional ' || NEW.nome,
        auth.uid(),
        timezone('America/Sao_Paulo', now())
      );
    END IF;
  END IF;

  -- 3. Atualizar custo unitário gravado no adicional do pedido
  v_custo_adic := public.fn_calcular_custo_adicional(NEW.adicional_id);
  IF v_custo_adic > 0 THEN
    UPDATE public.pedido_item_adicionais
    SET custo = v_custo_adic
    WHERE id = NEW.id;
  END IF;

  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- 9. RPC get_admin_reports Atualizada com CMV e Margem por Produto
CREATE OR REPLACE FUNCTION public.get_admin_reports(
  p_inicio TIMESTAMPTZ,
  p_fim TIMESTAMPTZ,
  p_categoria_id TEXT DEFAULT NULL
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  v_user_role TEXT;
  v_cortesias JSONB;
  v_mais_vendidos JSONB;
  v_pagamentos JSONB;
  v_promocoes JSONB;
  v_tempo_preparo JSONB;
  v_horarios_pico_hora JSONB;
  v_horarios_pico_dia JSONB;
  v_ticket_medio JSONB;
  v_margem_produtos JSONB;
  v_cmv_resumo JSONB;
BEGIN
  -- Validar role (apenas admin pode rodar)
  v_user_role := public.get_user_role();
  IF v_user_role != 'admin' THEN
    RAISE EXCEPTION 'Acesso negado.';
  END IF;

  -- 1. Cortesias concedidas
  SELECT COALESCE(jsonb_agg(row_to_json(t)), '[]'::jsonb) INTO v_cortesias
  FROM (
    SELECT
      pi_origem.nome_produto AS prato_liberador,
      SUM(pi_cortesia.quantidade) AS total_cortesias,
      SUM(pi_cortesia.quantidade * pi_cortesia.preco_unitario) AS valor_abonado,
      SUM(pi_cortesia.quantidade * COALESCE(pi_cortesia.custo_unitario, 0)) AS custo_cortesias
    FROM public.pedido_itens pi_cortesia
    JOIN public.pedido_itens pi_origem ON pi_cortesia.cortesia_de_item_id = pi_origem.id
    JOIN public.pedidos p ON p.id = pi_cortesia.pedido_id
    WHERE pi_cortesia.cortesia_de_item_id IS NOT NULL
      AND pi_cortesia.cancelado = false
      AND p.status != 'cancelado'
      AND p.created_at >= p_inicio
      AND p.created_at <= p_fim
    GROUP BY pi_origem.nome_produto
    ORDER BY total_cortesias DESC
  ) t;

  -- 2. Mais Vendidos
  SELECT COALESCE(jsonb_agg(row_to_json(t)), '[]'::jsonb) INTO v_mais_vendidos
  FROM (
    SELECT 
      pi.nome_produto,
      SUM(pi.quantidade) AS quantidade_vendida,
      SUM(pi.quantidade * pi.preco_unitario) AS faturamento
    FROM public.pedido_itens pi
    JOIN public.pedidos p ON p.id = pi.pedido_id
    WHERE pi.cancelado = false
      AND p.status != 'cancelado'
      AND p.created_at >= p_inicio
      AND p.created_at <= p_fim
      AND (p_categoria_id IS NULL OR p_categoria_id = '' OR pi.categoria_id = p_categoria_id)
    GROUP BY pi.nome_produto
    ORDER BY quantidade_vendida DESC
    LIMIT 100
  ) t;

  -- 3. Pagamentos
  SELECT COALESCE(jsonb_agg(row_to_json(t)), '[]'::jsonb) INTO v_pagamentos
  FROM (
    SELECT
      forma,
      SUM(valor) AS total_valor
    FROM (
      SELECT fp.forma, fp.valor
      FROM public.fechamento_pagamentos fp
      JOIN public.fechamentos f ON f.id = fp.fechamento_id
      WHERE f.created_at >= p_inicio AND f.created_at <= p_fim
      UNION ALL
      SELECT p.forma_pagamento AS forma, p.total AS valor
      FROM public.pedidos p
      LEFT JOIN public.fechamento_pedidos fped ON fped.pedido_id = p.id
      WHERE fped.pedido_id IS NULL
        AND p.status_pagamento = 'pago'
        AND p.status != 'cancelado'
        AND p.forma_pagamento IS NOT NULL
        AND p.created_at >= p_inicio AND p.created_at <= p_fim
    ) todas_formas
    GROUP BY forma
    ORDER BY total_valor DESC
  ) t;

  -- 4. Promoções (com lucro com e sem desconto)
  SELECT COALESCE(jsonb_agg(row_to_json(t)), '[]'::jsonb) INTO v_promocoes
  FROM (
    SELECT 
      prom.nome AS promocao_nome,
      COUNT(pi.id) AS vezes_aplicada,
      SUM(pi.desconto) AS desconto_total,
      SUM(pi.quantidade * pi.preco_unitario) AS faturamento,
      SUM(pi.quantidade * COALESCE(pi.custo_unitario, 0)) AS custo_total,
      SUM(pi.quantidade * pi.preco_unitario) - SUM(pi.quantidade * COALESCE(pi.custo_unitario, 0)) AS lucro_com_desconto,
      (SUM(pi.quantidade * pi.preco_unitario) + SUM(COALESCE(pi.desconto, 0))) - SUM(pi.quantidade * COALESCE(pi.custo_unitario, 0)) AS lucro_sem_desconto
    FROM public.pedido_itens pi
    JOIN public.pedidos p ON p.id = pi.pedido_id
    JOIN public.promocoes prom ON prom.id = pi.promocao_id
    WHERE pi.promocao_id IS NOT NULL
      AND pi.cancelado = false
      AND p.status != 'cancelado'
      AND p.created_at >= p_inicio
      AND p.created_at <= p_fim
    GROUP BY prom.nome
    ORDER BY desconto_total DESC
  ) t;

  -- 5. Tempo de preparo
  SELECT row_to_json(t) INTO v_tempo_preparo
  FROM (
    SELECT 
      COALESCE(AVG(EXTRACT(EPOCH FROM (iniciado_em - created_at))/60), 0) AS media_fila_minutos,
      COALESCE(AVG(EXTRACT(EPOCH FROM (concluido_em - iniciado_em))/60), 0) AS media_preparo_minutos
    FROM public.pedidos
    WHERE status IN ('concluido', 'entregue')
      AND iniciado_em IS NOT NULL
      AND concluido_em IS NOT NULL
      AND created_at >= p_inicio
      AND created_at <= p_fim
  ) t;

  -- 6. Horários de pico - Por Hora
  SELECT COALESCE(jsonb_agg(row_to_json(t)), '[]'::jsonb) INTO v_horarios_pico_hora
  FROM (
    SELECT 
      EXTRACT(HOUR FROM (created_at AT TIME ZONE 'America/Sao_Paulo')) AS hora,
      COUNT(id) AS total_pedidos,
      SUM(total) AS faturamento
    FROM public.pedidos
    WHERE status != 'cancelado'
      AND created_at >= p_inicio
      AND created_at <= p_fim
    GROUP BY hora
    ORDER BY hora ASC
  ) t;

  -- 7. Horários de pico - Por Dia
  SELECT COALESCE(jsonb_agg(row_to_json(t)), '[]'::jsonb) INTO v_horarios_pico_dia
  FROM (
    SELECT 
      EXTRACT(DOW FROM (created_at AT TIME ZONE 'America/Sao_Paulo')) AS dia,
      COUNT(id) AS total_pedidos,
      SUM(total) AS faturamento
    FROM public.pedidos
    WHERE status != 'cancelado'
      AND created_at >= p_inicio
      AND created_at <= p_fim
    GROUP BY dia
    ORDER BY dia ASC
  ) t;

  -- 8. Ticket Médio e Resumo Geral
  SELECT row_to_json(t) INTO v_ticket_medio
  FROM (
    SELECT 
      COALESCE(SUM(total), 0) AS faturamento_total,
      COUNT(id) AS pedidos_validos,
      CASE 
        WHEN COUNT(id) > 0 THEN COALESCE(SUM(total), 0) / COUNT(id)
        ELSE 0 
      END AS ticket_medio
    FROM public.pedidos
    WHERE status != 'cancelado'
      AND created_at >= p_inicio
      AND created_at <= p_fim
  ) t;

  -- 9. Margem e Lucro por Produto (CAF-000032)
  SELECT COALESCE(jsonb_agg(row_to_json(t)), '[]'::jsonb) INTO v_margem_produtos
  FROM (
    SELECT 
      pi.produto_id,
      pi.nome_produto,
      SUM(pi.quantidade) AS quantidade_vendida,
      SUM(pi.quantidade * pi.preco_unitario) AS faturamento,
      SUM(pi.quantidade * COALESCE(pi.custo_unitario, 0)) AS custo_total,
      SUM(pi.quantidade * pi.preco_unitario) - SUM(pi.quantidade * COALESCE(pi.custo_unitario, 0)) AS lucro_bruto,
      CASE 
        WHEN SUM(pi.quantidade * pi.preco_unitario) > 0 
        THEN ROUND(((SUM(pi.quantidade * pi.preco_unitario) - SUM(pi.quantidade * COALESCE(pi.custo_unitario, 0))) / SUM(pi.quantidade * pi.preco_unitario) * 100)::numeric, 1)
        ELSE 0 
      END AS margem_percentual
    FROM public.pedido_itens pi
    JOIN public.pedidos p ON p.id = pi.pedido_id
    WHERE pi.cancelado = false
      AND p.status != 'cancelado'
      AND p.created_at >= p_inicio
      AND p.created_at <= p_fim
      AND (p_categoria_id IS NULL OR p_categoria_id = '' OR pi.categoria_id = p_categoria_id)
    GROUP BY pi.produto_id, pi.nome_produto
    ORDER BY faturamento DESC
  ) t;

  -- 10. Resumo de CMV e Lucro Bruto do Período (CAF-000032)
  SELECT row_to_json(t) INTO v_cmv_resumo
  FROM (
    WITH totais AS (
      SELECT 
        COALESCE(SUM(pi.quantidade * pi.preco_unitario), 0) AS faturamento_total,
        COALESCE(SUM(pi.quantidade * COALESCE(pi.custo_unitario, 0)), 0) AS custo_total
      FROM public.pedido_itens pi
      JOIN public.pedidos p ON p.id = pi.pedido_id
      WHERE pi.cancelado = false
        AND p.status != 'cancelado'
        AND p.created_at >= p_inicio
        AND p.created_at <= p_fim
    ),
    cortesias AS (
      SELECT 
        COALESCE(SUM(pi_cortesia.quantidade * COALESCE(pi_cortesia.custo_unitario, 0)), 0) AS custo_cortesias
      FROM public.pedido_itens pi_cortesia
      JOIN public.pedidos p ON p.id = pi_cortesia.pedido_id
      WHERE pi_cortesia.cortesia_de_item_id IS NOT NULL
        AND pi_cortesia.cancelado = false
        AND p.status != 'cancelado'
        AND p.created_at >= p_inicio
        AND p.created_at <= p_fim
    )
    SELECT 
      totais.faturamento_total,
      totais.custo_total AS cmv_total,
      (totais.faturamento_total - totais.custo_total) AS lucro_bruto_total,
      CASE 
        WHEN totais.faturamento_total > 0 
        THEN ROUND((totais.custo_total / totais.faturamento_total * 100)::numeric, 1)
        ELSE 0 
      END AS cmv_percentual,
      CASE 
        WHEN totais.faturamento_total > 0 
        THEN ROUND(((totais.faturamento_total - totais.custo_total) / totais.faturamento_total * 100)::numeric, 1)
        ELSE 0 
      END AS margem_media_percentual,
      cortesias.custo_cortesias
    FROM totais, cortesias
  ) t;

  RETURN jsonb_build_object(
    'cortesias', v_cortesias,
    'mais_vendidos', v_mais_vendidos,
    'pagamentos', v_pagamentos,
    'promocoes', v_promocoes,
    'tempo_preparo', v_tempo_preparo,
    'horarios_pico_hora', v_horarios_pico_hora,
    'horarios_pico_dia', v_horarios_pico_dia,
    'resumo', v_ticket_medio,
    'margem_produtos', v_margem_produtos,
    'cmv_resumo', v_cmv_resumo
  );
END;
