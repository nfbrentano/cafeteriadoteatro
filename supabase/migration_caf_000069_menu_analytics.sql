-- 1. Tabela agregada de eventos diários do cardápio e autoatendimento
CREATE TABLE IF NOT EXISTS public.cardapio_eventos_diarios (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  data DATE NOT NULL DEFAULT CURRENT_DATE,
  canal TEXT NOT NULL CHECK (canal IN ('mesa', 'retirada', 'totem', 'vitrine', 'geral')),
  tipo_evento TEXT NOT NULL CHECK (tipo_evento IN ('sessao_cardapio', 'view_item', 'add_to_cart', 'begin_checkout', 'purchase')),
  produto_id TEXT REFERENCES public.produtos(id) ON DELETE CASCADE,
  total_eventos INT NOT NULL DEFAULT 1,
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('America/Sao_Paulo', now()),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('America/Sao_Paulo', now()),
  CONSTRAINT uq_cardapio_evento_diario UNIQUE NULLS NOT DISTINCT (data, canal, tipo_evento, produto_id)
);

CREATE INDEX IF NOT EXISTS idx_cardapio_eventos_data ON public.cardapio_eventos_diarios(data, canal);
CREATE INDEX IF NOT EXISTS idx_cardapio_eventos_prod ON public.cardapio_eventos_diarios(produto_id);

-- 2. RPC com UPSERT atômico para registrar/incrementar contadores do funil
CREATE OR REPLACE FUNCTION public.registrar_evento_cardapio(
  p_canal TEXT,
  p_tipo_evento TEXT,
  p_produto_id TEXT DEFAULT NULL,
  p_data DATE DEFAULT CURRENT_DATE
) RETURNS VOID AS $$
BEGIN
  INSERT INTO public.cardapio_eventos_diarios (data, canal, tipo_evento, produto_id, total_eventos, updated_at)
  VALUES (COALESCE(p_data, CURRENT_DATE), p_canal, p_tipo_evento, p_produto_id, 1, timezone('America/Sao_Paulo', now()))
  ON CONFLICT (data, canal, tipo_evento, produto_id)
  DO UPDATE SET
    total_eventos = public.cardapio_eventos_diarios.total_eventos + 1,
    updated_at = timezone('America/Sao_Paulo', now());
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;
