-- 1. Tabela de Lotes de Estoque
CREATE TABLE IF NOT EXISTS public.estoque_lotes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  item_id BIGINT NOT NULL REFERENCES public.estoque_itens(id) ON DELETE CASCADE,
  lote_codigo TEXT,
  data_validade DATE,
  quantidade_inicial NUMERIC(12,3) NOT NULL CHECK (quantidade_inicial > 0),
  quantidade_restante NUMERIC(12,3) NOT NULL CHECK (quantidade_restante >= 0),
  custo_unitario NUMERIC(10,4),
  movimento_entrada_id BIGINT REFERENCES public.estoque_movimentos(id) ON DELETE SET NULL,
  ativo BOOLEAN NOT NULL DEFAULT true,
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('America/Sao_Paulo', now()),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('America/Sao_Paulo', now())
);

-- Índices para aceleração do PEPS e consultas de validade
CREATE INDEX IF NOT EXISTS idx_estoque_lotes_item_peps
  ON public.estoque_lotes (item_id, data_validade ASC NULLS LAST, created_at ASC)
  WHERE quantidade_restante > 0 AND ativo = true;

CREATE INDEX IF NOT EXISTS idx_estoque_lotes_validade_alerta
  ON public.estoque_lotes (data_validade)
  WHERE quantidade_restante > 0 AND ativo = true;

-- 2. Colunas de referência de lote em estoque_movimentos
ALTER TABLE public.estoque_movimentos
  ADD COLUMN IF NOT EXISTS lote_id BIGINT REFERENCES public.estoque_lotes(id) ON DELETE SET NULL,
  ADD COLUMN IF NOT EXISTS lote_codigo TEXT;

CREATE INDEX IF NOT EXISTS idx_estoque_movimentos_lote_id
  ON public.estoque_movimentos(lote_id)
  WHERE lote_id IS NOT NULL;

-- 3. Habilitar RLS e Políticas de Segurança em estoque_lotes
