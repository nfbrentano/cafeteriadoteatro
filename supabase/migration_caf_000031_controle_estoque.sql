-- 1. Tabela de Itens de Estoque (Produtos de Revenda e Insumos)
CREATE TABLE IF NOT EXISTS public.estoque_itens (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome TEXT NOT NULL,
  unidade TEXT NOT NULL CHECK (unidade IN ('un','g','kg','ml','l')),
  quantidade NUMERIC(12,3) NOT NULL DEFAULT 0,
  estoque_minimo NUMERIC(12,3) NOT NULL DEFAULT 0,
  custo_medio NUMERIC(10,4) NOT NULL DEFAULT 0,
  codigo_barras TEXT,
  controla_validade BOOLEAN NOT NULL DEFAULT false,
  ativo BOOLEAN NOT NULL DEFAULT true,
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('America/Sao_Paulo', now()),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('America/Sao_Paulo', now())
);

-- Índices auxiliares
CREATE INDEX IF NOT EXISTS idx_estoque_itens_nome ON public.estoque_itens(nome);
CREATE INDEX IF NOT EXISTS idx_estoque_itens_codigo_barras ON public.estoque_itens(codigo_barras) WHERE codigo_barras IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_estoque_itens_minimo ON public.estoque_itens(quantidade, estoque_minimo) WHERE ativo = true;

-- 2. Tabela de Movimentos de Estoque
CREATE TABLE IF NOT EXISTS public.estoque_movimentos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  item_id BIGINT NOT NULL REFERENCES public.estoque_itens(id) ON DELETE CASCADE,
  tipo TEXT NOT NULL CHECK (tipo IN ('entrada','saida_venda','estorno','ajuste','perda')),
  quantidade NUMERIC(12,3) NOT NULL,
  custo_unitario NUMERIC(10,4),
  validade DATE,
  pedido_item_id BIGINT REFERENCES public.pedido_itens(id) ON DELETE SET NULL,
  motivo TEXT,
  criado_por UUID REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('America/Sao_Paulo', now())
);

CREATE INDEX IF NOT EXISTS idx_estoque_movimentos_item_id ON public.estoque_movimentos(item_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_estoque_movimentos_pedido_item ON public.estoque_movimentos(pedido_item_id) WHERE pedido_item_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_estoque_movimentos_validade ON public.estoque_movimentos(validade) WHERE validade IS NOT NULL;

-- 3. Vínculo em produtos e adicionais
ALTER TABLE public.produtos
  ADD COLUMN IF NOT EXISTS estoque_item_id BIGINT REFERENCES public.estoque_itens(id) ON DELETE SET NULL,
  ADD COLUMN IF NOT EXISTS esgotado_automatico BOOLEAN NOT NULL DEFAULT false;

CREATE INDEX IF NOT EXISTS idx_produtos_estoque_item ON public.produtos(estoque_item_id) WHERE estoque_item_id IS NOT NULL;

ALTER TABLE public.adicionais
  ADD COLUMN IF NOT EXISTS estoque_item_id BIGINT REFERENCES public.estoque_itens(id) ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS idx_adicionais_estoque_item ON public.adicionais(estoque_item_id) WHERE estoque_item_id IS NOT NULL;

-- 4. Função e Trigger para Recalcular Saldo e Custo Médio Ponderado
CREATE OR REPLACE FUNCTION public.fn_estoque_recalcular_saldo()
RETURNS TRIGGER AS $$
DECLARE
  v_item_id BIGINT;
  v_novo_saldo NUMERIC(12,3);
  v_custo_medio_atual NUMERIC(10,4);
  v_saldo_anterior NUMERIC(12,3);
BEGIN
  v_item_id := COALESCE(NEW.item_id, OLD.item_id);

  SELECT quantidade, custo_medio INTO v_saldo_anterior, v_custo_medio_atual
  FROM public.estoque_itens
  WHERE id = v_item_id;

  -- Somar movimentos:
  -- 'entrada' e 'estorno' somam
  -- 'saida_venda' e 'perda' subtraem
  -- 'ajuste' adiciona delta
  SELECT COALESCE(SUM(
    CASE 
      WHEN tipo IN ('entrada', 'estorno') THEN quantidade
      WHEN tipo IN ('saida_venda', 'perda') THEN -quantidade
      WHEN tipo = 'ajuste' THEN quantidade
      ELSE 0
    END
  ), 0)
  INTO v_novo_saldo
  FROM public.estoque_movimentos
  WHERE item_id = v_item_id;

  -- Se for uma nova ENTRADA com custo_unitario informado, recalcular o Custo Médio Ponderado:
  IF TG_OP = 'INSERT' AND NEW.tipo = 'entrada' AND NEW.custo_unitario IS NOT NULL AND NEW.custo_unitario > 0 THEN
    IF v_saldo_anterior IS NOT NULL AND v_saldo_anterior > 0 AND v_custo_medio_atual > 0 THEN
      v_custo_medio_atual := ((v_saldo_anterior * v_custo_medio_atual) + (NEW.quantidade * NEW.custo_unitario)) / (v_saldo_anterior + NEW.quantidade);
    ELSE
      v_custo_medio_atual := NEW.custo_unitario;
    END IF;
  END IF;

  UPDATE public.estoque_itens
  SET quantidade = v_novo_saldo,
      custo_medio = COALESCE(v_custo_medio_atual, custo_medio),
      updated_at = timezone('America/Sao_Paulo', now())
  WHERE id = v_item_id;

  RETURN COALESCE(NEW, OLD);
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS trg_estoque_recalcular_saldo ON public.estoque_movimentos;
CREATE TRIGGER trg_estoque_recalcular_saldo
  AFTER INSERT OR UPDATE OR DELETE ON public.estoque_movimentos
  FOR EACH ROW
  EXECUTE FUNCTION public.fn_estoque_recalcular_saldo();

-- 5. Função e Trigger para Sincronizar Disponibilidade de Produto (Esgotado Automático)
CREATE OR REPLACE FUNCTION public.fn_estoque_sincronizar_disponibilidade_produto()
RETURNS TRIGGER AS $$
BEGIN
  -- Caso 1: Saldo zerou ou ficou negativo
  IF NEW.quantidade <= 0 AND (OLD.quantidade > 0 OR OLD.quantidade IS NULL) THEN
    -- Desativar produtos de revenda vinculados que estavam disponíveis
    UPDATE public.produtos
    SET disponivel = false,
        esgotado_automatico = true,
        updated_at = timezone('America/Sao_Paulo', now())
    WHERE estoque_item_id = NEW.id AND disponivel = true;
  END IF;

  -- Caso 2: Saldo voltou a ficar positivo
  IF NEW.quantidade > 0 AND OLD.quantidade <= 0 THEN
    -- Reativar apenas os produtos que foram esgotados automaticamente pelo estoque
    UPDATE public.produtos
    SET disponivel = true,
        esgotado_automatico = false,
        updated_at = timezone('America/Sao_Paulo', now())
    WHERE estoque_item_id = NEW.id AND esgotado_automatico = true AND disponivel = false;
  END IF;

  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS trg_estoque_sincronizar_disponibilidade ON public.estoque_itens;
CREATE TRIGGER trg_estoque_sincronizar_disponibilidade
  AFTER UPDATE OF quantidade ON public.estoque_itens
  FOR EACH ROW
  EXECUTE FUNCTION public.fn_estoque_sincronizar_disponibilidade_produto();

-- 6. Trigger para Baixa Automática de Estoque no Pedido Item
CREATE OR REPLACE FUNCTION public.fn_baixa_estoque_pedido_item()
RETURNS TRIGGER AS $$
DECLARE
  v_estoque_item_id BIGINT;
BEGIN
  IF NEW.cancelado = true THEN
    RETURN NEW;
  END IF;

  -- 1. Baixar produto principal se vinculado a estoque_itens
  SELECT estoque_item_id INTO v_estoque_item_id
  FROM public.produtos
  WHERE id = NEW.produto_id;

  IF v_estoque_item_id IS NOT NULL THEN
    INSERT INTO public.estoque_movimentos (
      item_id, tipo, quantidade, pedido_item_id, motivo, criado_por, created_at
    ) VALUES (
      v_estoque_item_id,
      'saida_venda',
      NEW.quantidade,
      NEW.id,
      'Venda Pedido #' || NEW.pedido_id,
      auth.uid(),
      timezone('America/Sao_Paulo', now())
    );
  END IF;

  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS trg_baixa_estoque_pedido_item ON public.pedido_itens;
CREATE TRIGGER trg_baixa_estoque_pedido_item
  AFTER INSERT ON public.pedido_itens
  FOR EACH ROW
  EXECUTE FUNCTION public.fn_baixa_estoque_pedido_item();

-- 7. Trigger para Baixa Automática de Adicionais com Estoque
CREATE OR REPLACE FUNCTION public.fn_baixa_estoque_adicional()
RETURNS TRIGGER AS $$
DECLARE
  v_estoque_item_id BIGINT;
  v_qtd_pai INT := 1;
BEGIN
  SELECT estoque_item_id INTO v_estoque_item_id
  FROM public.adicionais
  WHERE id = NEW.adicional_id;

  IF v_estoque_item_id IS NOT NULL THEN
    SELECT COALESCE(quantidade, 1) INTO v_qtd_pai
    FROM public.pedido_itens
    WHERE id = NEW.pedido_item_id;

    INSERT INTO public.estoque_movimentos (
      item_id, tipo, quantidade, pedido_item_id, motivo, criado_por, created_at
    ) VALUES (
      v_estoque_item_id,
      'saida_venda',
      (v_qtd_pai * COALESCE(NEW.quantidade, 1)),
      NEW.pedido_item_id,
      'Adicional ' || NEW.nome,
      auth.uid(),
      timezone('America/Sao_Paulo', now())
    );
  END IF;

  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS trg_baixa_estoque_adicional ON public.pedido_item_adicionais;
CREATE TRIGGER trg_baixa_estoque_adicional
  AFTER INSERT ON public.pedido_item_adicionais
  FOR EACH ROW
  EXECUTE FUNCTION public.fn_baixa_estoque_adicional();

-- 8. Trigger para Estorno no Cancelamento de Item
CREATE OR REPLACE FUNCTION public.fn_estorno_estoque_pedido_item()
RETURNS TRIGGER AS $$
DECLARE
  v_mov_rec RECORD;
BEGIN
  -- Quando o item é cancelado
  IF NEW.cancelado = true AND (OLD.cancelado = false OR OLD.cancelado IS NULL) THEN
    FOR v_mov_rec IN
      SELECT item_id, quantidade
      FROM public.estoque_movimentos
      WHERE pedido_item_id = NEW.id AND tipo = 'saida_venda'
    LOOP
      INSERT INTO public.estoque_movimentos (
        item_id, tipo, quantidade, pedido_item_id, motivo, criado_por, created_at
      ) VALUES (
        v_mov_rec.item_id,
        'estorno',
        v_mov_rec.quantidade,
        NEW.id,
        COALESCE(NEW.motivo_cancelamento, 'Item cancelado'),
        auth.uid(),
        timezone('America/Sao_Paulo', now())
      );
    END LOOP;
  END IF;

  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS trg_estorno_estoque_pedido_item ON public.pedido_itens;
CREATE TRIGGER trg_estorno_estoque_pedido_item
  AFTER UPDATE OF cancelado ON public.pedido_itens
  FOR EACH ROW
  EXECUTE FUNCTION public.fn_estorno_estoque_pedido_item();

-- 9. Trigger para Estorno quando o Pedido Inteiro é Cancelado
CREATE OR REPLACE FUNCTION public.fn_estorno_estoque_pedido_cancelado()
RETURNS TRIGGER AS $$
BEGIN
  IF NEW.status = 'cancelado' AND (OLD.status != 'cancelado' OR OLD.status IS NULL) THEN
    -- Cancelar todos os itens ativos que ainda não foram cancelados (dispara o trg_estorno_estoque_pedido_item)
    UPDATE public.pedido_itens
    SET cancelado = true,
        motivo_cancelamento = COALESCE(NEW.motivo_cancelamento, 'Pedido cancelado'),
        cancelado_em = COALESCE(cancelado_em, timezone('America/Sao_Paulo', now())),
        cancelado_por = COALESCE(cancelado_por, auth.uid())
    WHERE pedido_id = NEW.id AND cancelado = false;
  END IF;

  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS trg_estorno_estoque_pedido_cancelado ON public.pedidos;
CREATE TRIGGER trg_estorno_estoque_pedido_cancelado
  AFTER UPDATE OF status ON public.pedidos
  FOR EACH ROW
  EXECUTE FUNCTION public.fn_estorno_estoque_pedido_cancelado();

