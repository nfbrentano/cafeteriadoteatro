-- 9. View v_produto_alergenicos (Ficha Técnica ∪ Manuais)
CREATE OR REPLACE VIEW public.v_produto_alergenicos AS
WITH base AS (
  SELECT
    ft.produto_id,
    eia.alergenico_id,
    a.nome AS alergenico_nome,
    a.icone AS alergenico_icone,
    'contem'::text AS tipo,
    'ficha_tecnica'::text AS origem,
    COALESCE(eia.created_at, ft.created_at) AS ref_data
  FROM public.fichas_tecnicas ft
  JOIN public.estoque_item_alergenicos eia ON eia.estoque_item_id = ft.estoque_item_id
  JOIN public.alergenicos a ON a.id = eia.alergenico_id
  WHERE ft.produto_id IS NOT NULL

  UNION ALL

  SELECT
    pa.produto_id,
    pa.alergenico_id,
    a.nome AS alergenico_nome,
    a.icone AS alergenico_icone,
    pa.tipo::text AS tipo,
    'manual'::text AS origem,
    pa.created_at AS ref_data
  FROM public.produto_alergenicos pa
  JOIN public.alergenicos a ON a.id = pa.alergenico_id
)
SELECT DISTINCT ON (produto_id, alergenico_id)
  produto_id,
  alergenico_id,
  alergenico_nome,
  alergenico_icone,
  tipo,
  origem,
  ref_data
FROM base
ORDER BY produto_id, alergenico_id, (CASE WHEN tipo = 'contem' THEN 1 ELSE 2 END), (CASE WHEN origem = 'ficha_tecnica' THEN 1 ELSE 2 END);

