  p.nome AS produto_nome,
  p.alergenicos_revisado_em,
  p.alergenicos_revisado_por,
  CASE
    WHEN p.alergenicos_revisado_em IS NULL THEN 'nao_revisado'
    WHEN EXISTS (
      SELECT 1
      FROM public.fichas_tecnicas ft
      LEFT JOIN public.estoque_item_alergenicos eia ON eia.estoque_item_id = ft.estoque_item_id
      WHERE ft.produto_id = p.id
        AND (
          ft.created_at > p.alergenicos_revisado_em
          OR (eia.created_at IS NOT NULL AND eia.created_at > p.alergenicos_revisado_em)
        )
    ) OR EXISTS (
      SELECT 1
      FROM public.produto_alergenicos pa
      WHERE pa.produto_id = p.id
        AND pa.created_at > p.alergenicos_revisado_em
    ) THEN 'revisao_necessaria'
    ELSE 'revisado'
  END AS status_revisao
FROM public.produtos p;

