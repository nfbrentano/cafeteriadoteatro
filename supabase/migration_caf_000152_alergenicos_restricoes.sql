CREATE OR REPLACE FUNCTION public.fn_sync_pedidos_alergias()
RETURNS TRIGGER AS $$
DECLARE
  v_match text[];
BEGIN
  IF (NEW.alergias_cliente IS NULL OR cardinality(NEW.alergias_cliente) = 0) AND NEW.observacoes IS NOT NULL THEN
    v_match := regexp_matches(NEW.observacoes, 'alergia[:\s\/]+([^|\n\r]+)', 'i');
    IF v_match IS NOT NULL AND array_length(v_match, 1) > 0 THEN
      NEW.alergias_cliente := string_to_array(trim(v_match[1]), ', ');
    END IF;
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

